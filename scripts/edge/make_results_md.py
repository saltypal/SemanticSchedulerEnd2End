"""Write docs/RESULTS_ALL.md: every result under results/edge_final as Markdown tables (no runs, read-only).

    python -m scripts.edge.make_results_md
"""
import csv
import glob
import json
import os
from pathlib import Path

R = Path("results/edge_final")
OUT = Path("docs/RESULTS_ALL.md")


def name(p):
    pol = p["policy"]
    if pol.startswith("learned:"):
        parts = pol.split(":")
        return "%s (%s)" % (parts[1], os.path.basename(parts[2]))
    return pol


def table(cells, title):
    rows = []
    rows.append("\n#### %s\n" % title)
    rows.append("| policy | c | rho | CTR@D | 95% CI | value/image | Low starvation | redundant/100 | decision time (us) | per-tier timely (C/H/M/L) |")
    rows.append("|---|---:|---:|---:|---|---:|---:|---:|---:|---|")
    for p in sorted(cells, key=lambda x: (name(x), x["workers"], x["rho"])):
        ci = (p.get("ci95") or {}).get("ctr_ungated")
        tm = p.get("timely")
        tms = "/".join("%.2f" % t for t in tm) if isinstance(tm, list) else ""
        rows.append("| %s | %d | %.1f | %.3f | %s | %s | %s | %s | %s | %s |" % (
            name(p), p["workers"], p["rho"], p["ctr_ungated"],
            "[%.3f, %.3f]" % tuple(ci) if ci else "",
            "%.3f" % p["value"] if isinstance(p.get("value"), (int, float)) else "",
            "%.3f" % p["low_starvation"] if isinstance(p.get("low_starvation"), (int, float)) else "",
            "%.2f" % p["redundant_per_100"] if isinstance(p.get("redundant_per_100"), (int, float)) else "",
            "%.0f" % p["decision_time_mean_us"] if isinstance(p.get("decision_time_mean_us"), (int, float)) else "",
            tms))
    return rows


def main():
    L = ["# All results (2026-11-14)",
         "",
         "Generated by `python -m scripts.edge.make_results_md` from the files in `results/edge_final/`. CTR@D = fraction "
         "of human-labelled Critical images decoded before the Critical deadline. c = decoder workers (one GPU each), "
         "rho = offered load. 95% CIs are bootstrap over 5 trace realisations. Validation = California wildfires "
         "(2,485 images); test = Hurricane Maria + Mexico earthquake (8,585 images), run once with frozen settings. "
         "`-tuned` files use the tuned SV-DPP configuration (V 0.1, purge 0.99, relevance beta 1.0, tie tolerance 0.5). "
         "`spi_edf_ratio` = header-aware value-rate batching; `edf_ratio` = same batch rule without the header.",
         "", "## 1. Full-split sweeps (Kaggle)"]
    for f in sorted(glob.glob(str(R / "kaggle_full" / "*.json"))):
        d = json.load(open(f))
        L += table(d.get("cells", []), os.path.basename(f))
    L += ["", "## 2. Subsample sweeps (1,000 validation / 2,000 test images; laptop)"]
    for f in sorted(glob.glob(str(R / "subsample" / "*.json"))):
        d = json.load(open(f))
        L += table(d.get("cells", []), os.path.basename(f))
    L += ["", "## 3. Uplink sensitivity (AWGN / Rayleigh, 10 kHz, 1,000 validation images)"]
    for f in sorted(glob.glob(str(R / "link" / "*.json"))):
        d = json.load(open(f))
        L += table(d.get("cells", []), os.path.basename(f))
    L += ["", "## 4. SV-DPP tuning grid (relevance beta x tie tolerance; 1,000 validation images, c = 2, rho = 1.2, 3 realisations)", "",
          "| beta | tie_tol | CTR@D |", "|---:|---:|---:|"]
    with open(R / "tuning" / "sv_dpp_beta_tie_grid.csv") as fh:
        for r in csv.DictReader(fh):
            L.append("| %s | %s | %s |" % (r["beta"], r["tie"], r["ctr"]))
    L += ["", "One-knob SV-DPP diagnostic on a 1,000-image validation subset (c = 2, rho = 1.2, 5 realisations): tuned 0.323; "
          "V = 1.0 0.324; tie 0.3 0.303; tie 0.1 0.286; beta 0.5 0.331; purge 0.95 0.316; untuned 0.293 (script "
          "`results/edge_final/tuning/diag.py`).",
          "", "## 5. Semantic audit (Claude Haiku, low effort; 300 validation images, c = 2, rho = 1.2)", ""]
    L.append("| policy | decisions | semantic precision | inversions/100 | Kendall tau | Critical wait (s) | Low wait (s) | CTR@D |")
    L.append("|---|---:|---:|---:|---:|---:|---:|---:|")
    with open(R / "audit" / "summary.csv") as fh:
        for r in csv.DictReader(fh):
            L.append("| %s | %s | %.2f | %.1f | %.2f | %.2f | %.2f | %.2f |" % (
                os.path.basename(r["policy"]), r["n_decisions"], float(r["semantic_precision"]),
                float(r["inversions_per_100"]), float(r["kendall_tau"]), float(r["wait_critical"]),
                float(r["wait_low"]), float(r["ctr"])))
    L += ["", "Full audit text: `results/edge_final/audit/AUDIT_REPORT.md`.",
          "", "## 6. Other measured numbers",
          "- Codec v1 batched decode latency on one T4 (median, m = 0.25): B = 1/2/4/8 -> 0.74 / 1.46 / 2.88 / 3.86 s.",
          "- Payload 464 B for all 27,044 images at m = 0.25; mean LPIPS of reconstructions 0.466.",
          "- SPI head on validation: macro-F1 0.567, Critical recall 0.818 / precision 0.683, High recall 0.079, ECE 0.024.",
          "- Header bit depth: 8-bit SPI / relevance flip 8.2% / 7.9% of SV-DPP decisions; 16-bit < 0.5%; STS 4-bit 0 flips.",
          "- Uplink delay / loss: AWGN 10 dB 0.122 s / 0%; AWGN 0 dB 0.422 s / 0%; Rayleigh 20 dB 0.125 s / 1.1%; "
          "Rayleigh 10 dB 0.261 s / 4.6%; Rayleigh 0 dB 0.947 s / 10.1%.",
          "- Splits: train C 1,218 / H 1,047 / M 3,653 / L 10,056; val C 499 / H 139 / M 429 / L 1,418; "
          "test C 760 / H 492 / M 1,892 / L 5,441; 124 cross-split near-duplicates removed."]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
